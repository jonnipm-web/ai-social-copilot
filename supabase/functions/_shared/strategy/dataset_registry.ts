export const DATASET_REGISTRY: readonly DatasetRecord[] = Object.freeze([SYNTHETIC_5MIN_DATASET, WIN1_REAL_DATASET]);

const BY_ID: ReadonlyMap<string, DatasetRecord> = new Map(DATASET_REGISTRY.map((d) => [d.datasetId, d]));

export function getDataset(datasetId: string): DatasetRecord | undefined {
  return BY_ID.get(datasetId);
}

export function isKnownDataset(datasetId: string): boolean {
  return BY_ID.has(datasetId);
}
