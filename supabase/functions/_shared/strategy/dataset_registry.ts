/**
 * Dataset Registry — INSIGHTVALUES-ROBOT-BUILDER-MACRO-06 §16-17.
 *
 * A strategy references a `datasetId`, never a filesystem path (§16: "Do
 * not allow arbitrary server filesystem paths"). This is a closed
 * allowlist -- resolving a dataset always goes through `getDataset`,
 * which either returns a known, fully-described record or nothing. There
 * is no code path anywhere in this module that turns caller-supplied text
 * into a path.
 *
 * `winReal5min` deliberately carries NO row data and no file path here --
 * only metadata (§17: the real WIN1! dataset stays UNCLEAR/NOT_DISTRIBUTED,
 * kept local to the external Python worktree per Macro-05's finding). Its
 * `sourceRef` is a free-text provenance pointer, never resolved by this
 * module; only the Python bridge (backtest_bridge.ts), which runs outside
 * this repository's own execution boundary, knows how to reach it.
 */

export type DatasetLicenseStatus = 'SYNTHETIC_FIXTURE' | 'UNCLEAR_NOT_DISTRIBUTED' | 'USER_PROVIDED';
export type DatasetVerificationState = 'CERTIFIED' | 'CERTIFIED_WITH_WARNINGS' | 'UNVERIFIED';

export interface DatasetRecord {
  readonly datasetId: string;
  readonly instrumentSymbol: string;
  readonly market: string;
  readonly timeframe: string;
  readonly periodStart: string;
  readonly periodEnd: string;
  readonly hash: string;
  readonly rowCount: number;
  readonly licenseStatus: DatasetLicenseStatus;
  readonly verificationState: DatasetVerificationState;
  /** Free-text provenance. For SYNTHETIC_FIXTURE, describes how the data
   * was generated. For UNCLEAR_NOT_DISTRIBUTED, points at the external
   * location -- never a path this module or any Edge Function resolves
   * itself. */
  readonly sourceRef: string;
  /** Rows are embedded in-process (small, generated fixtures) vs resolved
   * externally by a specific engine's own bridge (e.g. the Python
   * service). This module never reads a file for either case. */
  readonly rowsAvailableInProcess: boolean;
}

